package ClassesNConstructors.Inheritance.Polymorphism;

public class Casting {

    public static void main(String[] args) {

        int a = 10;
        int b = 3;

        double c = (double) a/b;
        // Type Casting : when you want to store one type of value into another type
        // then use that type in round brackets in front of the value to be stored

        System.out.println("c="+c);
    }
}
