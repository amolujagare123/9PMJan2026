package StringsDemo;

public class SubstringDemo {

    public static void main(String[] args) {
        String str1 = "where are you";
        System.out.println(str1.substring(6));

        String str2 = "switch is at some height";
        System.out.println(str2.substring(10));

        System.out.println(str2.substring(4,13));
        System.out.println(str2.substring(5,15));





    }
}
